--Q13
SELECT d.EMP_ID, d.FIRST_NAME, d.LAST_NAME, d.EXP, d.ROLE AS ASSIGNED_ROLE,
  CASE WHEN d.EXP <= 2 THEN 'JUNIOR DATA SCIENTIST'
       WHEN d.EXP > 2  AND d.EXP <= 5  THEN 'ASSOCIATE DATA SCIENTIST'
       WHEN d.EXP > 5  AND d.EXP <= 10 THEN 'SENIOR DATA SCIENTIST'
       WHEN d.EXP > 10 AND d.EXP <= 12 THEN 'LEAD DATA SCIENTIST'
       WHEN d.EXP > 12 AND d.EXP <= 16 THEN 'MANAGER' END AS STANDARD_ROLE,
  CASE WHEN d.ROLE = CASE WHEN d.EXP <= 2 THEN 'JUNIOR DATA SCIENTIST'
       WHEN d.EXP > 2  AND d.EXP <= 5  THEN 'ASSOCIATE DATA SCIENTIST'
       WHEN d.EXP > 5  AND d.EXP <= 10 THEN 'SENIOR DATA SCIENTIST'
       WHEN d.EXP > 10 AND d.EXP <= 12 THEN 'LEAD DATA SCIENTIST'
       WHEN d.EXP > 12 AND d.EXP <= 16 THEN 'MANAGER' END
       THEN 'MATCH' ELSE 'NO MATCH' END AS CHECK_RESULT
FROM data_science_team d;

