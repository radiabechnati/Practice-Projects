-- SQL Assessment: employee database (SQLite)

-- Q1 Create database 'employee' & create 3 tables
CREATE TABLE proj_table (
    PROJECT_ID TEXT PRIMARY KEY, 
    PROJ_NAME TEXT, 
    DOMAIN TEXT, 
    START_DATE TEXT,
    CLOSURE_DATE TEXT, 
DEV_QTR TEXT, 
STATUS TEXT
);

CREATE TABLE emp_record_table (
    EMP_ID TEXT PRIMARY KEY,
    FIRST_NAME TEXT,
    LAST_NAME TEXT,
    GENDER TEXT,
    ROLE TEXT,
    DEPT TEXT,
    EXP INTEGER,
    COUNTRY TEXT,
    CONTINENT TEXT,
    SALARY INTEGER,
    EMP_RATING INTEGER,
    MANAGER_ID TEXT,
    PROJ_ID TEXT,
    FOREIGN KEY (MANAGER_ID) REFERENCES emp_record_table(EMP_ID),
    FOREIGN KEY (PROJ_ID) REFERENCES proj_table(PROJECT_ID)
);

CREATE TABLE data_science_team (
    EMP_ID TEXT PRIMARY KEY,
    FIRST_NAME TEXT,
    LAST_NAME TEXT,
    GENDER TEXT,
    ROLE TEXT,
    DEPT TEXT,
    EXP INTEGER,
    COUNTRY TEXT,
    CONTINENT TEXT,
    FOREIGN KEY (EMP_ID) REFERENCES emp_record_table(EMP_ID)
);


SELECT (SELECT COUNT(*) FROM proj_table) AS proj,
      (SELECT COUNT(*) FROM emp_record_table) AS emp,
      (SELECT COUNT(*) FROM data_science_team) AS ds;

